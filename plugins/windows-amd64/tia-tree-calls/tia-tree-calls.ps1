param(
    [switch]$Help,
    [string]$InputFile = "block_calls.json",
    [string[]]$Entry = @(),
    [string]$OutputFile = "",
    [string[]]$Type = @(),
    [int]$Level = 0
)

if ($Help) {
    @"
Usage: .\tree_calls.ps1 [-InputFile <path>] [-Entry <name[]>] [-OutputFile <path>] [-Type <type[]>] [-Level <n>] [-Help]

Description:
  Reads a block call graph (generated by scan_calls.ps1) and outputs a visual
  tree of the call hierarchy, showing only block names.

Options:
  -InputFile   Path to the JSON call graph file (default: block_calls.json)
  -Entry       One or more entry block names to start the tree from.
               If omitted, shows all top-level blocks (not called by any other block).
  -OutputFile  File path to write output. If omitted, prints to console.
  -Type        Filter blocks by type (e.g. FB, FC, DB, OB, UDT). Multiple types allowed.
               If omitted, all types are included.
  -Level       Maximum expansion depth: 1=direct children, 2=grandchildren, etc.
               0 = unlimited recursive expansion (default).
  -Help        Show this help message.

Examples:
  .\tree_calls.ps1
  .\tree_calls.ps1 -Entry "OB_Program_Cycle"
  .\tree_calls.ps1 -Entry "FB_Bin_Control","FB_Hoist_Control" -Level 1
  .\tree_calls.ps1 -Type FB,FC
  .\tree_calls.ps1 -Level 2
  .\tree_calls.ps1 -Entry "OB_Main" -Level 3 -Type FB
  .\tree_calls.ps1 -InputFile "custom.json" -OutputFile "tree.txt"
"@
    exit 0
}

$ErrorActionPreference = "Stop"

$baseDir = Split-Path -Parent $PSCommandPath

$inputPath = if ([System.IO.Path]::IsPathRooted($InputFile)) { $InputFile } else { Join-Path $baseDir $InputFile }
if (-not (Test-Path -LiteralPath $inputPath)) {
    Write-Error "Input file not found: $inputPath"
    exit 1
}

Write-Host "Reading $inputPath ..."
$rawData = Get-Content -LiteralPath $inputPath -Raw -Encoding UTF8 | ConvertFrom-Json

$blockMap = @{}
foreach ($block in $rawData) {
    $names = @($block.use | ForEach-Object { $_.name })
    $blockMap[$block.name] = @{
        type = $block.type
        use  = $names
    }
}

$allNames = $blockMap.Keys

if (-not $Entry) {
    $calledBy = [System.Collections.Generic.HashSet[string]]::new()
    foreach ($block in $rawData) {
        foreach ($callee in $block.use) {
            [void]$calledBy.Add($callee.name)
        }
    }
    $Entry = @($allNames | Where-Object { -not $calledBy.Contains($_) } | Sort-Object)
}

if ($Type.Count -gt 0) {
    $Entry = @($Entry | Where-Object { $blockMap[$_].type -in $Type })
}

$Entry = @($Entry | Select-Object -Unique)

$script:TypeFilter = @($Type)
$script:MaxDepth   = $Level

$treeLines = [System.Collections.ArrayList]::new()

$pipe  = [char]0x2502
$tee   = [char]0x251c
$elbow = [char]0x2514
$dash  = [char]0x2500

function Write-Tree {
    param(
        [string]$Name,
        [string[]]$Ancestors,
        [string]$Indent,
        [bool]$IsLast,
        [int]$Depth
    )

    if ($Depth -gt 0) {
        $connector = if ($IsLast) { "$elbow$dash$dash " } else { "$tee$dash$dash " }
    }

    [void]$treeLines.Add("$Indent$connector$Name")

    $isDuplicate = $Ancestors -contains $Name

    if (-not $isDuplicate -and $blockMap.ContainsKey($Name)) {
        $children = $blockMap[$Name].use
        if ($script:TypeFilter.Count -gt 0) {
            $children = @($children | Where-Object {
                $blockMap[$_].type -in $script:TypeFilter
            })
        }
        $childCount = $children.Count

        $childIndent = if ($Depth -eq 0) { "" } else { $Indent + $(if ($IsLast) { "    " } else { "$pipe   " }) }

        for ($j = 0; $j -lt $childCount; $j++) {
            $child = $children[$j]
            $childIsLast = ($j -eq $childCount - 1)

            $stopRecurse = ($script:MaxDepth -gt 0 -and $Depth -ge $script:MaxDepth)
            if (-not $stopRecurse) {
                Write-Tree -Name $child -Ancestors ($Ancestors + $Name) -Indent $childIndent -IsLast $childIsLast -Depth ($Depth + 1)
            }
        }
    }
}

Write-Host "Building tree ..."
for ($i = 0; $i -lt $Entry.Count; $i++) {
    $entryName = $Entry[$i]
    if (-not $blockMap.ContainsKey($entryName)) {
        Write-Warning "Entry block not found in call graph: $entryName"
        continue
    }
    Write-Tree -Name $entryName -Ancestors @() -Indent "" -IsLast $false -Depth 0
    if ($i -lt $Entry.Count - 1) {
        [void]$treeLines.Add("")
    }
}

$outputStr = $treeLines -join "`r`n"

if ($OutputFile) {
    $outputPath = if ([System.IO.Path]::IsPathRooted($OutputFile)) { $OutputFile } else { Join-Path $baseDir $OutputFile }
    Set-Content -LiteralPath $outputPath -Value $outputStr -Encoding UTF8
    Write-Host "Written to $outputPath"
}
else {
    Write-Host ""
    Write-Host $outputStr
}
